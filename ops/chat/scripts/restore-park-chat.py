#!/usr/bin/env python3
import os, socket, pathlib, subprocess

ROOT = pathlib.Path("/opt/relay/state/park-tls")
CERTS = ROOT / "certs"
OUT = ROOT / "Caddyfile.parked"
UPSTREAM = os.environ.get("RELAY_HTTP_PORT", "8080")

def local_chat():
    s = socket.socket(); s.settimeout(0.2)
    try:
        s.connect(("127.0.0.1", 8098)); return True
    except Exception:
        return False
    finally:
        s.close()

def chat_block():
    if local_chat():
        return (
            "\t# flashback-chat-sidecar\n"
            "\thandle /chat/api* {\n"
            "\t\treverse_proxy 127.0.0.1:8098\n"
            "\t}\n"
            "\thandle /chat/ws {\n"
            "\t\treverse_proxy 127.0.0.1:8098\n"
            "\t}\n"
        )
    return (
        "\t# flashback-chat-sidecar\n"
        "\thandle /chat/api* {\n"
        "\t\treverse_proxy https://iad1.relaygateway.net {\n"
        "\t\t\theader_up Host flashbackrepository.org\n"
        "\t\t\ttransport http {\n"
        "\t\t\t\ttls_server_name flashbackrepository.org\n"
        "\t\t\t}\n"
        "\t\t}\n"
        "\t}\n"
        "\thandle /chat/ws {\n"
        "\t\treverse_proxy https://iad1.relaygateway.net {\n"
        "\t\t\theader_up Host flashbackrepository.org\n"
        "\t\t\ttransport http {\n"
        "\t\t\t\ttls_server_name flashbackrepository.org\n"
        "\t\t\t}\n"
        "\t\t}\n"
        "\t}\n"
    )

hosts = sorted([p.name for p in CERTS.iterdir() if p.is_dir()]) if CERTS.is_dir() else []
parts = ["# Generated by relay-gateway park_tls plugin - do not edit\n"]
chat = chat_block()
any_host = False
for host in hosts:
    chain = CERTS / host / "fullchain.pem"
    key = CERTS / host / "privkey.pem"
    if not (chain.is_file() and key.is_file()):
        continue
    any_host = True
    if host.startswith("www.") and len(host) > 4:
        apex = host[4:]
        parts.append(
            host + " {\n"
            "\ttls " + str(chain) + " " + str(key) + "\n"
            "\tredir https://" + apex + "{uri} permanent\n"
            "}\n\n"
        )
        continue
    # Mesh chat on every parked apex (Flashback Ergo; local or proxy).
    inject = chat
    parts.append(
        host + " {\n"
        "\ttls " + str(chain) + " " + str(key) + "\n"
        + inject
        + "\treverse_proxy 127.0.0.1:" + UPSTREAM + " {\n"
        "\t\ttransport http {\n"
        "\t\t\tdial_timeout 2s\n"
        "\t\t\tresponse_header_timeout 35s\n"
        "\t\t}\n"
        "\t}\n"
        "}\n\n"
    )
if not any_host:
    parts.append("# (no park-tls certificates installed yet)\n")
text = "".join(parts)
tmp = OUT.parent / "Caddyfile.parked.tmp"
tmp.write_text(text)
os.replace(tmp, OUT)
print("wrote", OUT, "bytes", OUT.stat().st_size)
# show flashback site
start = text.find("flashbackrepository.org {")
print(text[start:start+450] if start >= 0 else "NO FLASHBACK")
adapt_path = "/var/tmp/caddy-adapted-%d.json" % os.getpid()
r = subprocess.run(["caddy", "adapt", "--config", "/etc/caddy/Caddyfile"], capture_output=True)
if r.returncode != 0:
    print("adapt failed", r.stderr.decode()[:500])
    raise SystemExit(1)
open(adapt_path, "wb").write(r.stdout)
subprocess.check_call([
    "curl", "-fsS", "-X", "POST", "http://127.0.0.1:2019/load",
    "-H", "Content-Type: application/json",
    "--data-binary", "@" + adapt_path,
])
print("LOAD_OK")
