#!/usr/bin/env bash
# Rewrite park-tls Caddyfile with /chat handles on every parked apex.
# Idempotent and structural (does not regex-splice nested reverse_proxy blocks).
set -euo pipefail

PARKED="${1:-/opt/relay/state/park-tls/Caddyfile.parked}"
CERTS="${CHAT_CADDY_CERTS:-/opt/relay/state/park-tls/certs}"
MODE="${CHAT_CADDY_MODE:-local}" # local = 127.0.0.1 chat-edge; remote = proxy to iad1

if [[ ! -d "${CERTS}" ]]; then
  echo "missing certs dir ${CERTS}" >&2
  exit 1
fi

python3 - "$PARKED" "$CERTS" "$MODE" <<'PY'
import os
import sys

parked, certs, mode = sys.argv[1:4]
hosts = sorted(
    d
    for d in os.listdir(certs)
    if os.path.isdir(os.path.join(certs, d))
    and os.path.isfile(os.path.join(certs, d, "fullchain.pem"))
    and os.path.isfile(os.path.join(certs, d, "privkey.pem"))
)

if mode == "local":
    chat = """\t# flashback-chat-sidecar
\thandle /chat/api* {
\t\treverse_proxy 127.0.0.1:8098
\t}
\thandle /chat/ws {
\t\treverse_proxy 127.0.0.1:8098
\t}
"""
else:
    chat = """\t# flashback-chat-sidecar
\thandle /chat/api* {
\t\treverse_proxy https://iad1.relaygateway.net {
\t\t\theader_up Host flashbackrepository.org
\t\t\ttransport http {
\t\t\t\ttls_server_name flashbackrepository.org
\t\t\t}
\t\t}
\t}
\thandle /chat/ws {
\t\treverse_proxy https://iad1.relaygateway.net {
\t\t\theader_up Host flashbackrepository.org
\t\t\ttransport http {
\t\t\t\ttls_server_name flashbackrepository.org
\t\t\t}
\t\t}
\t}
"""

rp = """\treverse_proxy 127.0.0.1:8080 {
\t\ttransport http {
\t\t\tdial_timeout 2s
\t\t\tresponse_header_timeout 35s
\t\t}
\t}
"""

out = ["# Generated by relay-gateway park_tls plugin - do not edit\n"]
for host in hosts:
    chain = f"{certs}/{host}/fullchain.pem"
    key = f"{certs}/{host}/privkey.pem"
    if host.startswith("www.") and len(host) > 4:
        apex = host[4:]
        out.append(
            f"{host} {{\n\ttls {chain} {key}\n\tredir https://{apex}{{uri}} permanent\n}}\n\n"
        )
        continue
    out.append(f"{host} {{\n\ttls {chain} {key}\n{chat}{rp}}}\n\n")

text = "".join(out)
os.makedirs(os.path.dirname(parked) or ".", exist_ok=True)
tmp = parked + ".tmp"
with open(tmp, "w") as f:
    f.write(text)
os.replace(tmp, parked)
print(f"patched {parked} mode={mode} hosts={len(hosts)}")
PY

if command -v caddy >/dev/null && [[ -f /etc/caddy/Caddyfile ]]; then
  caddy validate --config /etc/caddy/Caddyfile >/dev/null
  if curl -fsS http://127.0.0.1:2019/config/ >/dev/null 2>&1; then
    adapt="$(mktemp)"
    caddy adapt --config /etc/caddy/Caddyfile >"${adapt}"
    curl -fsS -X POST http://127.0.0.1:2019/load \
      -H 'Content-Type: application/json' \
      --data-binary @"${adapt}" >/dev/null
    rm -f "${adapt}"
  else
    systemctl reload caddy 2>/dev/null || systemctl restart caddy 2>/dev/null || true
  fi
fi

echo "Caddy park file updated: ${PARKED}"
